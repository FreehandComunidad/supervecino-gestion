-- Esquema base de SÚPERVECINO GESTIÓN.
-- Supabase Auth provee auth.users; el propietario y empleados se crean allí.
create table if not exists public.profiles (
 id uuid primary key references auth.users(id) on delete cascade,
 full_name text not null,
 role text not null default 'cashier' check (role in ('owner','manager','cashier')),
 active boolean not null default true,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.categories (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 active boolean not null default true,
 created_at timestamptz not null default now()
);
create table if not exists public.products (
 id uuid primary key default gen_random_uuid(),
 barcode text,
 sku text,
 name text not null,
 category_id uuid references public.categories(id),
 unit text not null default 'unidad',
 sale_price numeric(14,2) not null default 0 check (sale_price >= 0),
 cost_price numeric(14,2) not null default 0 check (cost_price >= 0),
 stock numeric(14,3) not null default 0,
 min_stock numeric(14,3) not null default 0,
 manages_stock boolean not null default true,
 active boolean not null default true,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create table if not exists public.customers (
 id uuid primary key default gen_random_uuid(),
 name text not null,
 document_number text,
 phone text,
 email text,
 address text,
 created_at timestamptz not null default now()
);
create table if not exists public.sales (
 id uuid primary key default gen_random_uuid(),
 sale_number bigint generated by default as identity unique,
 sold_at timestamptz not null default now(),
 status text not null default 'completed' check (status in ('completed','voided','refunded')),
 receipt_type text not null default 'internal' check (receipt_type in ('internal','fiscal')),
 customer_id uuid references public.customers(id),
 cashier_id uuid references public.profiles(id),
 subtotal numeric(14,2) not null check (subtotal >= 0),
 discount numeric(14,2) not null default 0 check (discount >= 0),
 total numeric(14,2) not null check (total >= 0),
 notes text,
 fiscal_point_of_sale integer,
 fiscal_voucher_type integer,
 fiscal_voucher_number bigint,
 fiscal_cae text,
 fiscal_cae_due_date date,
 fiscal_response jsonb,
 created_at timestamptz not null default now()
);
create table if not exists public.sale_items (
 id uuid primary key default gen_random_uuid(),
 sale_id uuid not null references public.sales(id) on delete cascade,
 product_id uuid references public.products(id),
 product_name text not null,
 barcode text,
 quantity numeric(14,3) not null check (quantity > 0),
 unit text not null default 'unidad',
 unit_price numeric(14,2) not null check (unit_price >= 0),
 discount numeric(14,2) not null default 0 check (discount >= 0),
 line_total numeric(14,2) not null check (line_total >= 0)
);
create table if not exists public.payments (
 id uuid primary key default gen_random_uuid(),
 sale_id uuid not null references public.sales(id) on delete cascade,
 method text not null check (method in ('cash','debit','credit','transfer','wallet','other')),
 amount numeric(14,2) not null check (amount > 0),
 reference text,
 created_at timestamptz not null default now()
);
create table if not exists public.stock_movements (
 id uuid primary key default gen_random_uuid(),
 product_id uuid not null references public.products(id),
 movement_type text not null check (movement_type in ('sale','purchase','adjustment','return','void')),
 quantity_delta numeric(14,3) not null,
 reference_id uuid,
 notes text,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);
create table if not exists public.cash_sessions (
 id uuid primary key default gen_random_uuid(),
 opened_by uuid not null references public.profiles(id),
 opened_at timestamptz not null default now(),
 opening_amount numeric(14,2) not null default 0 check (opening_amount >= 0),
 closed_by uuid references public.profiles(id),
 closed_at timestamptz,
 closing_amount numeric(14,2) check (closing_amount >= 0),
 expected_amount numeric(14,2),
 notes text
);
create table if not exists public.cash_movements (
 id uuid primary key default gen_random_uuid(),
 session_id uuid not null references public.cash_sessions(id),
 movement_type text not null check (movement_type in ('in','out','sale','refund')),
 amount numeric(14,2) not null check (amount > 0),
 description text not null,
 created_by uuid references public.profiles(id),
 created_at timestamptz not null default now()
);
create table if not exists public.app_settings (
 key text primary key,
 value jsonb not null,
 updated_at timestamptz not null default now()
);

-- Índices para consultas operativas y claves foráneas.
create index if not exists products_name_search_idx on public.products using gin (to_tsvector('simple', name));
create index if not exists products_barcode_idx on public.products(barcode);
create index if not exists products_category_id_idx on public.products(category_id);
create index if not exists sales_sold_at_idx on public.sales(sold_at desc);
create index if not exists sales_cashier_idx on public.sales(cashier_id);
create index if not exists sales_customer_id_idx on public.sales(customer_id);
create index if not exists sale_items_sale_idx on public.sale_items(sale_id);
create index if not exists sale_items_product_id_idx on public.sale_items(product_id);
create index if not exists payments_sale_idx on public.payments(sale_id);
create index if not exists stock_movements_product_idx on public.stock_movements(product_id);
create index if not exists stock_movements_created_by_idx on public.stock_movements(created_by);
create index if not exists cash_sessions_open_idx on public.cash_sessions(closed_at);
create index if not exists cash_sessions_opened_by_idx on public.cash_sessions(opened_by);
create index if not exists cash_sessions_closed_by_idx on public.cash_sessions(closed_by);
create index if not exists cash_movements_session_idx on public.cash_movements(session_id);
create index if not exists cash_movements_created_by_idx on public.cash_movements(created_by);

